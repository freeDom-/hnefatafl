"""Genuine cross-version deployment tests with historical source code.

These tests are mandatory in the dedicated CI job that fetches pinned tags/commits
and builds the production frontend. They use actual 0.40.0/0.41.0 code extracted
from the trusted repository, databases generated by historical code, and real
Uvicorn subprocesses. Historical source trees are never committed.
"""

from __future__ import annotations

import fcntl
import json
import socket
import sqlite3
from pathlib import Path

import pytest

import historical_release_support as support
from deployment_fixtures import TEST_RELEASE_DIGEST, legacy_snapshot

from hnefatafl.deployment import Deployment, DeploymentError
from hnefatafl.storage import SCHEMA_VERSION, Store

FIXTURE = Path(__file__).with_name("historical_fixture.py")
LIFESPAN = Path(__file__).with_name("historical_lifespan_under_lock.py")
HARNESS = Path(__file__).with_name("historical_updater_harness.py")
SMOKE = Path(__file__).with_name("target_application_smoke.py")
PASSWORD = "historical-release-fixture-password"
ORIGIN = "https://example.test"


def free_port() -> int:
    with socket.socket() as sock:
        sock.bind(("127.0.0.1", 0))
        return sock.getsockname()[1]


def application_env(port: int) -> str:
    return (
        "HNEFATAFL_ENV=production\n"
        f"HNEFATAFL_PUBLIC_URL={ORIGIN}\n"
        f"HNEFATAFL_PORT={port}\n"
        "HNEFATAFL_HOST=127.0.0.1\n"
        "HNEFATAFL_ALLOWED_HOSTS=example.test,127.0.0.1,localhost\n"
        "HNEFATAFL_TRUSTED_PROXIES=127.0.0.1\n"
        "HNEFATAFL_REGISTRATION_ENABLED=false\n"
        "HNEFATAFL_ONLINE_ENABLED=true\n"
    )


class NoSystemdDeployment(Deployment):
    def __init__(self, root: Path, data: Path):
        super().__init__(
            {"port": free_port(), "public_url": ORIGIN},
            base=root / "opt",
            data=data,
            etc=root / "etc",
            unit_file=root / "unit.service",
        )
        self.actions = []

    def service(self, action):
        self.actions.append("service:" + action)

    def run(self, args, **kwargs):
        self.actions.append([str(value) for value in args])


def sources(tmp_path):
    support.require_inputs()
    old = support.extract(support.REF_040, tmp_path / "historical-0.40.0")
    schema20 = support.extract(support.REF_SCHEMA20, tmp_path / "historical-schema20")
    assert support.package_version(old) == "0.40.0"
    assert support.schema_version(old) == 15
    assert support.package_version(schema20) == "0.40.0"
    assert support.schema_version(schema20) == 20
    support.prepare_release(old, "0.40.0", frontend_dist=support.FRONTEND_DIST)
    return old, schema20


def historical_data(tmp_path, old, schema20, schema):
    data = tmp_path / "data"
    manifest_path = tmp_path / "manifest.json"
    support.fixture(FIXTURE, old, "create-0.40", data, manifest_path)
    created = json.loads(manifest_path.read_text())
    assert created["schema"] == 15
    if schema == 20:
        support.fixture(FIXTURE, schema20, "upgrade-schema20", data, manifest_path)
        manifest = json.loads(manifest_path.read_text())
        assert manifest["schema"] == 20
    elif schema != 15:
        raise AssertionError(f"Unsupported historical schema {schema}")
    else:
        manifest = created
    return data, manifest


def layout(tmp_path, old):
    base = tmp_path / "opt"
    target = support.make_target_release(base / "releases/0.41.1")
    assert support.release_module_path(target).is_relative_to(target.resolve())
    (base / "current").symlink_to(old)
    etc = tmp_path / "etc"
    etc.mkdir()
    port = free_port()
    (etc / "application.env").write_text(application_env(port))
    (etc / "installed.json").write_text(json.dumps({"version": "0.40.0"}) + "\n")
    return base, target, etc, port


def harness(tmp_path, base, target, data, etc, port, *, action="deploy", fail=None):
    config = tmp_path / "harness.json"
    result = tmp_path / "harness-result.json"
    log = tmp_path / "target-app.log"
    config.write_text(
        json.dumps(
            {
                "action": action,
                "deployment": {"port": port, "public_url": ORIGIN},
                "base": str(base),
                "data": str(data),
                "etc": str(etc),
                "unit_file": str(etc / "hnefatafl.service"),
                "target": str(target),
                "result": str(result),
                "log": str(log),
                "fail_readiness": fail,
            }
        )
        + "\n"
    )
    return config, result, log


def assert_cleanup(result, log):
    pid_file = log.with_suffix(".pid")
    assert not pid_file.exists()
    assert result["application_stopped"] is True
    assert result["application_exit_code"] is not None
    pid = result.get("application_pid")
    assert isinstance(pid, int) and support.process_gone(pid)


def assert_preserved(data, manifest):
    assert support.digest(data / "models/historical-model.bin") == manifest["model_sha256"]
    assert (
        support.digest(data / "jobs/historical-job/checkpoint.pt") == manifest["checkpoint_sha256"]
    )


def assert_snapshot(backup, data, manifest, schema):
    with sqlite3.connect(backup / "data/hnefatafl.sqlite3") as c:
        assert c.execute("PRAGMA user_version").fetchone()[0] == schema
    snapshot_manifest = json.loads((backup / "manifest.json").read_text())
    for name in (
        "data/hnefatafl.sqlite3",
        "data/models/historical-model.bin",
        "data/jobs/historical-job/checkpoint.pt",
    ):
        assert name in snapshot_manifest
    assert snapshot_manifest["data/models/historical-model.bin"] == manifest["model_sha256"]
    assert (
        snapshot_manifest["data/jobs/historical-job/checkpoint.pt"] == manifest["checkpoint_sha256"]
    )


@pytest.mark.parametrize("schema", [15, 20], ids=["direct-schema15", "authentic-schema20"])
def test_historical_040_updater_activates_corrected_app(tmp_path, schema):
    old, schema20 = sources(tmp_path)
    data, manifest = historical_data(tmp_path, old, schema20, schema)
    base, target, etc, port = layout(tmp_path, old)
    config, result_path, log = harness(tmp_path, base, target, data, etc, port)
    result = support.run_updater_harness(HARNESS, old, config, result_path, timeout=300)
    assert result["ok"], result
    assert_cleanup(result, log)
    assert (base / "current").resolve() == target
    assert json.loads((etc / "installed.json").read_text())["version"] == "0.41.1"
    transaction = json.loads((etc / "transaction.json").read_text())
    assert transaction["phase"] == "committed"
    assert transaction["target"] == str(target)
    with sqlite3.connect(data / "hnefatafl.sqlite3") as c:
        assert c.execute("PRAGMA user_version").fetchone()[0] == SCHEMA_VERSION
        for name, identifier in manifest["accounts"].items():
            row = c.execute(
                "SELECT username,role,email_verified_at FROM accounts WHERE id=?",
                (identifier,),
            ).fetchone()
            assert row is not None and row[0] == name
            assert row[1] == manifest["roles"][name]
            assert row[2] is not None
        assert (
            c.execute("SELECT COUNT(*) FROM jobs WHERE id=?", (manifest["job_id"],)).fetchone()[0]
            == 1
        )
        assert (
            c.execute(
                "SELECT COUNT(*) FROM games WHERE id=?", (manifest["local_game_id"],)
            ).fetchone()[0]
            == 1
        )
        if schema == 20:
            assert (
                c.execute(
                    "SELECT COUNT(*) FROM online_games WHERE id=?",
                    (manifest["online_game_id"],),
                ).fetchone()[0]
                == 1
            )
            assert (
                c.execute(
                    "SELECT COUNT(*) FROM player_tournaments WHERE id=?",
                    (manifest["player_tournament_id"],),
                ).fetchone()[0]
                == 1
            )
            for table, expected in manifest["historical_counts"].items():
                assert c.execute(f"SELECT COUNT(*) FROM {table}").fetchone()[0] == expected, table
    assert_preserved(data, manifest)
    smoke = tmp_path / "smoke.json"
    support.run_target_script(
        SMOKE,
        target,
        data,
        etc / "application.env",
        "--data",
        str(data),
        "--result",
        str(smoke),
        "--origin",
        ORIGIN,
        "--password",
        PASSWORD,
        timeout=120,
    )
    assert json.loads(smoke.read_text())["ok"], smoke.read_text()


@pytest.mark.parametrize("schema", [15, 20], ids=["schema15-snapshot", "schema20-snapshot"])
def test_historical_040_failed_activation_refuses_cross_schema_rollback(tmp_path, schema):
    old, schema20 = sources(tmp_path)
    data, manifest = historical_data(tmp_path, old, schema20, schema)
    base, target, etc, port = layout(tmp_path, old)
    config, result_path, log = harness(tmp_path, base, target, data, etc, port, fail="remove_admin")
    result = support.run_updater_harness(HARNESS, old, config, result_path, timeout=300)
    assert result["ok"] is False
    assert result["error_type"] == "ValueError"
    assert "Online schema changed; manual recovery is required" in result["error"]
    assert_cleanup(result, log)
    # The historical updater activated the target, then its schema-authority
    # check refused to replace the upgraded schema with the snapshot. It did not start
    # the old application against the newer database.
    assert (base / "current").resolve() == target
    assert result["actions"].count("service start") == 1
    assert json.loads((etc / "installed.json").read_text())["version"] == "0.40.0"
    transaction = json.loads((etc / "transaction.json").read_text())
    assert transaction["phase"] == "activated"
    backup = Path(transaction["backup"])
    with sqlite3.connect(data / "hnefatafl.sqlite3") as c:
        assert c.execute("PRAGMA user_version").fetchone()[0] == SCHEMA_VERSION
    assert_snapshot(backup, data, manifest, schema)
    assert_preserved(data, manifest)


def test_corrected_updater_rejects_explicit_rollback_with_incompatible_schema(tmp_path):
    old, schema20 = sources(tmp_path)
    data, manifest = historical_data(tmp_path, old, schema20, 20)
    base, target, etc, port = layout(tmp_path, old)
    deployment = NoSystemdDeployment(tmp_path, data)
    from hnefatafl.deployment import atomic_json

    # The historical application ran from the managed release directory on disk.
    previous = deployment.releases / "0.40.0"
    old.rename(previous)
    atomic_json(previous / ".release.json", {"version": "0.40.0", "sha256": TEST_RELEASE_DIGEST})
    deployment.activate(previous)
    backup = legacy_snapshot(deployment)
    deployment.activate(target)
    atomic_json(
        deployment.state,
        {
            "version": "0.41.1",
            "target": str(target),
            "previous": str(previous),
            "backup": str(backup),
        },
    )
    Store(data / "hnefatafl.sqlite3")  # live database advances to the current schema
    with sqlite3.connect(data / "hnefatafl.sqlite3") as c:
        assert c.execute("PRAGMA user_version").fetchone()[0] == SCHEMA_VERSION
    deployment.actions.clear()
    with pytest.raises(
        DeploymentError, match=f"Snapshot schema 20 differs from live schema {SCHEMA_VERSION}"
    ):
        deployment.recover(rollback=True)
    assert deployment.actions == []
    assert (base / "current").resolve() == target
    with sqlite3.connect(data / "hnefatafl.sqlite3") as c:
        assert c.execute("PRAGMA user_version").fetchone()[0] == SCHEMA_VERSION
    assert_snapshot(backup, data, manifest, 20)
    assert_preserved(data, manifest)


def test_authentic_schema21_upgrade_preserves_running_modern_tournament(tmp_path):
    support.require_inputs()
    old = support.extract(support.REF_040, tmp_path / "historical-0.40.0")
    previous = support.extract(support.REF_041, tmp_path / "historical-0.41.0")
    data, manifest_path = tmp_path / "data", tmp_path / "manifest.json"
    support.fixture(FIXTURE, old, "create-0.40", data, manifest_path)
    support.fixture(FIXTURE, previous, "upgrade-schema21", data, manifest_path)
    manifest = json.loads(manifest_path.read_text())
    identifier = manifest["player_tournament_id"]
    database = data / "hnefatafl.sqlite3"
    with sqlite3.connect(database) as c:
        assert c.execute("PRAGMA user_version").fetchone()[0] == 21
        active_games = c.execute(
            "SELECT * FROM online_games WHERE status='active' ORDER BY id"
        ).fetchall()
        assert len(active_games) == 2
        audit = c.execute("SELECT * FROM player_tournament_audit ORDER BY id").fetchall()
    store = Store(database)
    with store.connection() as c:
        assert c.execute("PRAGMA user_version").fetchone()[0] == SCHEMA_VERSION
        tournament = c.execute(
            "SELECT match_mode,progression_policy,status FROM player_tournaments WHERE id=?",
            (identifier,),
        ).fetchone()
        assert tuple(tournament) == ("sequential", "independent", "running")
        assert [
            tuple(row)
            for row in c.execute("SELECT * FROM online_games WHERE status='active' ORDER BY id")
        ] == active_games
        assert [
            tuple(row) for row in c.execute("SELECT * FROM player_tournament_audit ORDER BY id")
        ] == audit
        assert not c.execute("PRAGMA foreign_key_check").fetchall()


def test_historical_041_fails_under_exclusive_gate(tmp_path, monkeypatch):
    support.require_inputs()
    historical = support.extract(support.REF_041, tmp_path / "historical-0.41.0")
    assert support.package_version(historical) == "0.41.0"
    assert support.schema_version(historical) == 21
    current_data = tmp_path / "current-module-data"
    current_data.mkdir()
    Store(current_data / "hnefatafl.sqlite3")
    monkeypatch.setenv("HNEFATAFL_DATA_DIR", str(current_data))
    data = tmp_path / "data"
    data.mkdir()
    result_path = tmp_path / "result.json"
    gate = (data / ".deployment-gate").open("a+")
    fcntl.flock(gate, fcntl.LOCK_EX | fcntl.LOCK_NB)
    try:
        support.run_historical_script(
            LIFESPAN,
            historical,
            "--data",
            str(data),
            "--result",
            str(result_path),
            timeout=60,
        )
    finally:
        fcntl.flock(gate, fcntl.LOCK_UN)
        gate.close()
    result = json.loads(result_path.read_text())
    assert result["ok"] is False
    assert result["error_type"] == "OnlineError"
    assert "Deployment in progress" in result["error"]


@pytest.mark.parametrize("tag", [support.REF_0411, support.REF_042])
def test_released_legacy_backups_move_without_space_and_keep_rollback_reference(
    tmp_path, tag, monkeypatch
):
    import subprocess
    import sys

    from hnefatafl import deployment as updater_module
    from hnefatafl.deployment import (
        Deployment,
        FilesystemInfo,
        atomic_json,
        install_reviewed_updater,
    )

    support.require_inputs()
    source = support.extract(tag, tmp_path / "source")
    assert support.package_version(source) == tag
    data = tmp_path / "data"
    data.mkdir()
    (data / "models").mkdir()
    (data / "models/model.bin").write_bytes(b"historical model")
    with sqlite3.connect(data / "hnefatafl.sqlite3") as connection:
        connection.execute("CREATE TABLE sample(value TEXT)")
        connection.execute("INSERT INTO sample VALUES ('historical user data')")
    deployment = NoSystemdDeployment(tmp_path, data)
    old = deployment.releases / ("0.40.0" if tag == "0.41.1" else "0.41.1")
    current = deployment.releases / tag
    for release in (old, current):
        release.mkdir(parents=True)
        atomic_json(
            release / ".release.json", {"version": release.name, "sha256": TEST_RELEASE_DIGEST}
        )
    deployment.etc.mkdir()
    deployment.activate(old)
    atomic_json(deployment.state, {"version": old.name, "target": str(old)})
    legacy = data / "backups"
    legacy.mkdir(mode=0o700)
    command = """
import json, sys
from pathlib import Path
from hnefatafl.deployment import Deployment
assert Path(sys.modules[Deployment.__module__].__file__).is_relative_to(Path.cwd())
root = Path(sys.argv[1])
updater = Deployment({}, base=root/'opt', data=root/'data', etc=root/'etc')
print(json.dumps([str(updater.snapshot()) for _ in range(5)]))
"""
    generated = subprocess.run(
        [sys.executable, "-c", command, str(tmp_path)],
        cwd=source,
        check=True,
        capture_output=True,
        text=True,
        timeout=60,
    )
    backups = [Path(path) for path in json.loads(generated.stdout.splitlines()[-1])]
    identities = {backup.name: backup.stat().st_ino for backup in backups}
    referenced = backups[0]
    deployment.activate(current)
    committed = {
        "version": tag,
        "target": str(current),
        "previous": str(old),
        "backup": str(referenced),
        "phase": "committed",
    }
    atomic_json(deployment.state, committed)
    atomic_json(
        deployment.journal,
        {key: committed[key] for key in ("target", "previous", "backup", "phase")},
    )
    utilities, commands = tmp_path / "lib", tmp_path / "bin"
    utilities.mkdir()
    commands.mkdir()
    flat = (source / "hnefatafl/deployment.py").read_bytes()
    (utilities / "deployment.py").write_bytes(flat)
    for name in ("update", "backup"):
        wrapper = commands / f"hnefatafl-{name}"
        wrapper.write_bytes((source / f"scripts/linux/{name}.sh").read_bytes())
        wrapper.chmod(0o755)
    before = (deployment.state.read_bytes(), deployment.journal.read_bytes())
    monkeypatch.setattr(
        updater_module,
        "Deployment",
        lambda config, **kwargs: Deployment(
            config, base=deployment.base, data=deployment.data, backups=deployment.backups, **kwargs
        ),
    )
    install_reviewed_updater(
        Path(__file__).resolve().parents[1],
        deployment.etc,
        utilities,
        commands,
        tmp_path / "deployment.lock",
    )
    assert (utilities / "legacy-deployment.py").read_bytes() == flat
    assert (utilities / "deployment.py").read_bytes() != flat
    assert json.loads((utilities / "active.json").read_text())["abi"] >= 3
    assert before == (deployment.state.read_bytes(), deployment.journal.read_bytes())
    deployment.filesystem_info = lambda path: FilesystemInfo(1, Path(path), 1024, 16)
    deployment.ensure_layout()
    assert not legacy.exists()
    assert len(list(deployment.backups.iterdir())) == 5
    assert all(
        (deployment.backups / name).stat().st_ino == inode for name, inode in identities.items()
    )
    expected = str(deployment.backups / referenced.name)
    assert json.loads(deployment.state.read_text())["backup"] == expected
    assert json.loads(deployment.journal.read_text())["backup"] == expected
    deployment.cleanup(dry_run=False)
    assert len(list(deployment.backups.iterdir())) == 3 and Path(expected).exists()
    assert (data / "models/model.bin").read_bytes() == b"historical model"
    with sqlite3.connect(data / "hnefatafl.sqlite3") as connection:
        assert (
            connection.execute("SELECT value FROM sample").fetchone()[0] == "historical user data"
        )
